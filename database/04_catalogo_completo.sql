-- 3) Cargar en Cuenta: tipo, naturaleza, nivel y "acepta movimientos" se calculan del codigo
INSERT INTO Cuenta (Codigo, Nombre, Tipo, Naturaleza, Nivel, AceptaMovimientos, Activa)
SELECT c.Codigo,
       c.Nombre,
       CASE LEFT(c.Codigo, 1)
            WHEN '1' THEN 'Activo' WHEN '2' THEN 'Pasivo' WHEN '3' THEN 'Capital'
            WHEN '4' THEN 'Ingreso' WHEN '5' THEN 'Costo' ELSE 'Gasto' END,
       CASE WHEN LEFT(c.Codigo, 1) IN ('1', '5', '6') THEN 'Deudora' ELSE 'Acreedora' END,
       LEN(c.Codigo) - LEN(REPLACE(c.Codigo, '.', '')) + 1,
       CASE WHEN EXISTS (SELECT 1 FROM @c h WHERE h.Codigo LIKE c.Codigo + '.%') THEN 0 ELSE 1 END,
       1
FROM @c c
ORDER BY c.Codigo;

-- 4) Enlazar cada cuenta con su padre (el codigo sin el ultimo segmento)
UPDATE h
SET h.IdCuentaPadre = p.IdCuenta
FROM Cuenta h
JOIN Cuenta p ON p.Codigo = LEFT(h.Codigo, LEN(h.Codigo) - CHARINDEX('.', REVERSE(h.Codigo)))
WHERE h.Nivel > 1;

COMMIT TRANSACTION;

